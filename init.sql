CREATE EXTENSION IF NOT EXISTS timescaledb;

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100),
    email VARCHAR(255) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    category VARCHAR(50) NOT NULL,
    type VARCHAR(10) NOT NULL CHECK (type IN ('INFLOW', 'OUTFLOW')),
    amount NUMERIC(18, 2) NOT NULL,
    PRIMARY KEY (id, timestamp),
    CHECK ((type = 'INFLOW' AND amount >= 0) OR (type = 'OUTFLOW' AND amount <= 0))
);

SELECT create_hypertable('transactions', 'timestamp', if_not_exists => TRUE);
CREATE INDEX IF NOT EXISTS transactions_user_timestamp_idx ON transactions (user_id, timestamp DESC);
CREATE INDEX IF NOT EXISTS transactions_user_category_timestamp_idx ON transactions (user_id, category, timestamp DESC);

